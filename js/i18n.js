function updateLangButtonUI(lang) {
  const flagImgs = document.querySelectorAll(".lang-flag-img");
  const langLabels = document.querySelectorAll(".lang-label");

  // When viewing in English, show Egyptian flag and "العربية" to switch to Arabic
  // When viewing in Arabic, show UK flag and "English" to switch to English
  const targetFlagSrc = lang === "en" ? "assets/images/flag_egypt.svg" : "assets/images/flag_uk.svg";
  const targetFlagAlt = lang === "en" ? "علم مصر" : "UK Flag";
  const targetLabel = lang === "en" ? "العربية" : "English";

  flagImgs.forEach(img => {
    img.src = targetFlagSrc;
    img.alt = targetFlagAlt;
  });

  langLabels.forEach(label => {
    label.textContent = targetLabel;
  });
}

function loadCustomContent() {
  try {
    const raw = localStorage.getItem("alfakhama_custom_content");
    if (!raw) return;
    const custom = JSON.parse(raw);
    if (custom.en && typeof custom.en === "object") {
      Object.assign(translations.en, custom.en);
    }
    if (custom.ar && typeof custom.ar === "object") {
      Object.assign(translations.ar, custom.ar);
    }
  } catch (err) {
    console.warn("Could not load custom content:", err);
  }
}

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  
  // Ensure any custom content from CMS is merged before applying
  loadCustomContent();

  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = translations[lang][key];
      } else {
        el.innerHTML = translations[lang][key];
      }
    }
  });

  // Update Language toggle button flag and label
  updateLangButtonUI(lang);

  localStorage.setItem("alfakhama_lang", lang);
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

function toggleLanguage() {
  const nextLang = currentLang === "en" ? "ar" : "en";
  setLanguage(nextLang);
}

// Expose translations globally for admin CMS synchronization
window.alfakhamaTranslations = translations;
window.alfakhamaLoadCustomContent = loadCustomContent;

document.addEventListener("DOMContentLoaded", () => {
  loadCustomContent();
  const savedLang = localStorage.getItem("alfakhama_lang") || "en";
  setLanguage(savedLang);

  const langToggles = document.querySelectorAll(".lang-switch-btn");
  langToggles.forEach(btn => {
    btn.addEventListener("click", toggleLanguage);
  });

  // Instant cross-tab synchronization when Admin saves website content
  window.addEventListener("storage", (e) => {
    if (e.key === "alfakhama_custom_content") {
      loadCustomContent();
      setLanguage(currentLang);
    }
  });
});
